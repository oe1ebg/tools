# Assembles the deployable bundle in site/tools/ (git-ignored): a copy of
# tools/<tool>/ without Markdown and dotfiles, the manuals from docs/
# rendered to <name>/index.html, their images (img/: the screenshots from build/manual-img/, generated by
# the build and not committed, plus docs/static/), an overview page
# (index.html), manifest.json (version, commit, build time),
# sota-alerts/build-info.js (release and commit for its help; the other
# tools' build-info.js come from their own build steps) and the
# manuals' Markdown sources in docs/, for sites that render them in their
# own theme (they link MkDocs-style, as if docs/*.md sat next to img/ and
# the tool directories, e.g. content/tools/*.md on oe1ebg.at).
#
# Runs after the data and bundle steps (they write into tools/). Every link
# inside the bundle is relative and stays inside it, so site/tools/ works
# from any directory on any static webserver, including offline ones; the
# tools reach the manuals as ../confirm-anleitung/ and ../data-sources/.
#
# `just e2e` and `just vnu` serve site/ (so the tools are at /tools/<tool>/,
# as on oe1ebg.at), `just dist` packs site/tools/.
#
# A site that embeds the bundle (oe1ebg.at) may render docs/*.md itself and
# replace index.html and the rendered manuals; the tools don't depend on
# anything but the URLs ../<manual>/ and ../.

ROOT_DIR = Path(__file__).resolve().parent.parent
TOOLS_DIR = ROOT_DIR / "tools"
DOCS_DIR = ROOT_DIR / "docs"
OUT_DIR = ROOT_DIR / "site" / "tools"
MANUAL_IMG_DIR = ROOT_DIR / "build" / "manual-img"

# Source repository (REPO_URL in tools/shared/js/sources.js).
REPO_URL = "https://github.com/oe1ebg/tools"

IGNORE = shutil.ignore_patterns("*.md", ".*", "__pycache__")

# The manuals on the overview page, in this order: docs/<name>.md ->
# <name>/index.html, or docs/<name>/index.md for a manual with sub pages
# (the Notfunk manual: docs/notfunk-anleitung/{tutorial,manual,reference}/*.md,
# every page as name.de.md or name.en.md -> notfunk-anleitung/…/).
# Every other docs/**/*.md is rendered too, titled by its first heading.
MANUALS = {
    "confirm-anleitung": "Bestätigungsverkehr: Anleitung",
    "notfunk-anleitung": "Notfunk-Meldebuch: Anleitung",
    "notfunk-anleitung/index.en": "Notfunk logbook: guide (English)",
    "data-sources": "Datenquellen",
}

# Tools on the overview page: directory -> (title, description).
TOOLS = {
    "confirm": ("Bestätigungsverkehr", "Offline-Logbuch für Bestätigungs- und Check-in-Runden."),
    "notfunk": ("Notfunk-Meldebuch", "Offline-Meldebuch für den Notfunk (Entwurf)."),
    "netlog": ("Netlog", "Notizen für Funkrunden: Stationen, Live-Notizen, „Ich bin dran“, Runden und Rundenleitung (Deutsch/English)."),
    "adif": ("ADIF-Editor", "ADIF-Logs (.adi) ansehen, prüfen und bearbeiten."),
    "sota-alerts": ("SOTA Alerts Map", "SOTA-Alerts auf der Karte (braucht Internet)."),
    "wavelog-import": ("Wavelog-Import", "QSOs eines Wavelog-Logbuchs auf dieses Gerät holen (braucht Internet; die anderen Tools bleiben offline)."),
}

PAGE = """<!doctype html>
<html lang="de">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<script src="{up}shared/js/theme.js"></script>
<link rel="stylesheet" href="{up}shared/css/tools.css">
<link rel="stylesheet" href="{up}shared/css/docs.css">
</head>
<body>
<main class="doc">
{nav}
{body}
{footer}
</main>
</body>
</html>
"""


class RelinkProcessor(Treeprocessor):
    """Rewrites the docs' MkDocs-style links for the page rendered from
    docs/<src>: relative URLs are relative to the source file (a sub page
    links ../img/x.png and sibling.md), .md targets become the directory of
    their rendered page."""

    def __init__(self, md, src):
        super().__init__(md)
        self.src = src

    def run(self, root):
        for el in root.iter():
            for attr in ("href", "src"):
                url = el.get(attr)
                if url and not re.match(r"^([a-z][a-z0-9+.-]*:|#|/)", url, re.I):
                    el.set(attr, relink(url, self.src))


def page_dir(src: str) -> str:
    """Directory of the page rendered from docs/<src>, relative to the bundle
    ('' for the root): x.md -> x, d/index.md -> d, d/p.md -> d/p."""
    path = posixpath.splitext(src)[0]
    path = path.removesuffix(".de")   # name.de.md is the German edition (the page's own address)
    return posixpath.dirname(path) if posixpath.basename(path) == "index" else path


def relink(url: str, src: str = "x.md") -> str:
    path, _, frag = url.partition("#")
    frag = f"#{frag}" if frag else ""
    target = posixpath.normpath(posixpath.join(posixpath.dirname(src), path)) if path else ""
    is_page = target.endswith(".md")
    if is_page:
        target = page_dir(target)
    elif path.endswith("/"):
        target += "/"
    start = page_dir(src) or "."
    rel = posixpath.relpath(target or ".", start)
    if is_page or path.endswith("/"):
        rel = "./" if rel == "." else rel + "/"
    return f"{rel}{frag}"


class Relink(Extension):
    def __init__(self, src="x.md"):
        super().__init__()
        self.src = src

    def extendMarkdown(self, md):
        md.treeprocessors.register(RelinkProcessor(md, self.src), "relink", 0)


def render(md_text: str, src: str = "x.md") -> str:
    return markdown.markdown(
        md_text,
        extensions=["attr_list", "admonition", "tables", "toc", "md_in_html", "fenced_code", Relink(src)],
        output_format="html",
    )


def footer(version: str, sha: str) -> str:
    """Footer of the overview and the manuals: the source repository and
    this build's version and commit (linked when it is a real SHA, like
    commitUrl() in tools/shared/js/sources.js)."""
    commit = html.escape(sha)
    if re.fullmatch(r"[0-9a-f]{7,40}", sha):
        commit = f'<a href="{REPO_URL}/commit/{sha}">{sha[:7]}</a>'
    return (f'<footer class="doc-footer">Quellcode: <a href="{REPO_URL}">github.com/oe1ebg/tools</a>'
            f" · Version {html.escape(version)} (commit {commit})</footer>")


def sota_build_info(version: str, sha: str) -> str:
    """build-info.js of the SOTA Alerts Map (no build step of its own):
    `self.SOTA_BUILD = { commit, release }` for the foot of its help, like
    the offline tools' (scripts/offline_tool.py); release only for a
    version tag."""
    commit = sha[:7].lower() if re.fullmatch(r"[0-9a-fA-F]{7,40}", sha) else "dev"
    release = version if RELEASE_TAG_RE.fullmatch(version) else None
    return ("// Generated by scripts/build_site.py — do not edit.\n"
            f"self.SOTA_BUILD = {json.dumps({'commit': commit, 'release': release})};\n")


def page(title: str, body: str, up: str, home: bool, foot: str = "") -> str:
    nav = f'<p class="doc-nav"><a href="{up}">← Alle Tools</a></p>' if home else ""
    return PAGE.format(title=html.escape(title), up=up, nav=nav, body=body, footer=foot)


def git_sha() -> str:
    if os.environ.get("GIT_SHA"):
        return os.environ["GIT_SHA"]
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT_DIR,
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "dev"


DEV_STUB_RE = re.compile(r"\bdev\s*:\s*true\b")


def dev_stubs(tools_dir: Path = TOOLS_DIR) -> list[Path]:
    """precache.js files that are the development stub (`just dev-precache`),
    not a build's manifest: they must never be staged or released (the tool
    would never work offline)."""
    return [p for p in sorted(tools_dir.glob("*/precache.js")) if DEV_STUB_RE.search(p.read_text(encoding="utf-8"))]


def main() -> None:
    stubs = dev_stubs()
    if stubs:
        names = ", ".join(str(p.relative_to(ROOT_DIR)) for p in stubs)
        raise SystemExit(f"error: development stub {names} (just dev-precache); run `just build` first, it writes the real precache.js")
    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)
    version = os.environ.get("TOOLS_VERSION", "dev")
    sha = git_sha()
    foot = footer(version, sha)

    for src in sorted(p for p in TOOLS_DIR.iterdir() if p.is_dir() and not p.name.startswith(".")):
        if src.name != "shared" and not (src / "index.html").exists():
            print(f"skipped tools/{src.name}/ (no index.html yet)")
            continue
        shutil.copytree(src, OUT_DIR / src.name, ignore=IGNORE)
        print(f"staged tools/{src.name}/")
    if (OUT_DIR / "sota-alerts").is_dir():
        (OUT_DIR / "sota-alerts" / "build-info.js").write_text(sota_build_info(version, sha), encoding="utf-8")

    for md in sorted(DOCS_DIR.rglob("*.md")):
        src = md.relative_to(DOCS_DIR).as_posix()
        text = md.read_text(encoding="utf-8")
        name = page_dir(src)
        heading = re.match(r"# (.+)", text)
        title = MANUALS.get(name) or (heading.group(1).strip() if heading else name)
        up = "../" * (name.count("/") + 1)
        body = render(text, src)
        rendered = page(title, body, up, True, foot)
        if md.stem.endswith(".en"):   # the English edition of a page (name.en.md)
            rendered = rendered.replace('<html lang="de">', '<html lang="en">', 1)
        (OUT_DIR / name).mkdir(parents=True, exist_ok=True)
        (OUT_DIR / name / "index.html").write_text(rendered, encoding="utf-8")
        print(f"rendered docs/{src} -> {name}/index.html")
    # the manuals' screenshots: generated during the build, not committed
    # (tests/e2e/manual.shots.mjs, `just screenshots`)
    if MANUAL_IMG_DIR.is_dir():
        shutil.copytree(MANUAL_IMG_DIR, OUT_DIR / "img")
    else:
        (OUT_DIR / "img").mkdir()
    # the few pictures that are not screenshots of a page and stay committed
    # (docs/static/: the render of Notfunk's PDF printout)
    for static in sorted((DOCS_DIR / "static").glob("*.png")):
        shutil.copyfile(static, OUT_DIR / "img" / static.name)
    # downloads the manuals link to: the empty Notfunk form, made by the
    # tool's own drawing function (scripts/notfunk_vordruck.mjs)
    (OUT_DIR / "downloads").mkdir()
    try:
        subprocess.run(["node", str(ROOT_DIR / "scripts" / "notfunk_vordruck.mjs"), str(OUT_DIR / "downloads" / "notfunk-vordruck.pdf")], check=True)
    except (OSError, subprocess.CalledProcessError) as err:
        print(f"warning: downloads/notfunk-vordruck.pdf not made ({err}); the manual links to it")
    gone = missing_manual_images(OUT_DIR / "img")
    if gone:
        print(f"warning: {len(gone)} manual screenshot(s) not generated yet ({', '.join(gone[:3])}{', …' if len(gone) > 3 else ''}): `just build` makes them, `just screenshots` after `just stage`; a release requires them")
    (OUT_DIR / "docs").mkdir()
    for md in sorted(DOCS_DIR.rglob("*.md")):
        (OUT_DIR / "docs" / md.relative_to(DOCS_DIR)).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(md, OUT_DIR / "docs" / md.relative_to(DOCS_DIR))

    items = "\n".join(
        f'<li><a href="{d}/">{html.escape(t)}</a> — {html.escape(desc)}</li>'
        for d, (t, desc) in TOOLS.items() if (OUT_DIR / d).is_dir())
    docs = "\n".join(
        f'<li><a href="{n}/"{" lang=\"en\"" if n.endswith(".en") else ""}>{html.escape(t)}</a></li>'
        for n, t in MANUALS.items())
    body = f"<h1>Tools</h1>\n<ul>\n{items}\n</ul>\n<h2>Anleitungen</h2>\n<ul>\n{docs}\n</ul>"
    (OUT_DIR / "index.html").write_text(page("Tools", body, "", False, foot), encoding="utf-8")

    manifest = {
        "name": "oe1ebg-tools",
        "version": version,
        "commit": sha,
        "built": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    (OUT_DIR / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    n = sum(1 for p in OUT_DIR.rglob("*") if p.is_file())
    print(f"site/tools/: {n} files, version {manifest['version']} ({manifest['commit']})")


if __name__ == "__main__":
    main()
